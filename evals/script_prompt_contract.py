def fact(fid, claim, value, *, approved=True, conditions="", truth="stated"):
    return {"id": fid, "kind": "spec", "claim": claim, "value": value, "approved": approved,
            "conditions": conditions, "truth": truth, "confidence": 1,
            "source": {"ref": "source-doc", "locator": "page 4 / turbo column", "quote": f"{claim}: {value}"}}


def registry(category="compact suv"):
    return {"product": {"name": "Script fixture", "category": category, "summary": "A synthetic regression fixture.", "audience": "Buyers"},
            "brand": {"tone": "Warm", "voice_style": "Direct", "dos": [], "donts": [], "persona_hint": "Guide"},
            "facts": [fact("F001", "Turbo engine output", "160 PS", conditions="Turbo automatic only; exact source unit"),
                      fact("F002", "Petrol engine gearbox", "Automatic gearbox"),
                      fact("F003", "REJECTED CLAIM", "999 km", approved=False),
                      fact("F004", "Manufacturer shift description", "seamless shifts", truth="marketing")],
            "images": [{"id": "im1", "source_id": "source-image", "quality": 4, "angle": "engine bay",
                        "parts": [], "description": "Synthetic fixture image identity; no actual pixel claim"}],
            "shots": [], "unknowns": [], "image_map": {"F001": ["im1"]}, "competitors": []}


def line(text, citations=(), visual=""):
    return {"text": text, "step": "say", "fact_ids": list(citations),
            "visual": {"kind": "image" if visual else "none", "ref": visual, "focus": ""}, "card": "none"}


def draft(text, citations=(), visual=""):
    return {"segments": [{"id": "proof", "title": "Engine choice", "role": "proof", "topic": "powertrain",
                           "lines": [line(text, citations, visual)], "checkin": "", "deeper": []}],
            "closing": [], "intake_q1": "", "intake_q2": ""}


class CapturedAuthor(BaseException):
    """Stop immediately at the model boundary without running any provider."""


