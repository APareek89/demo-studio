# Intercept the actual assembled runtime envelopes. Coach's mock branch has no
# model call, so inspect its local envelope at the deterministic mock boundary.
original_coach_mock = coach.mock_playbook
languages = ("en-IN", "hi-IN", "hinglish")
for category in ("compact suv", "premium suv", "electric scooter", "unlisted industrial product"):
    for audience, language in zip(("everyday", "informed", "expert"), languages):
        und = registry(category)
        demo = store.new_demo("Prompt assembly regression")
        demo["product"].update(und["product"])
        demo["settings"].update(audience=audience, language=language, languages=[language], enhance_images="off")
        store.save(demo["id"], demo)
        store.write_json(demo["id"], "understanding.json", und)
        captured = {}
        def capture_coach(understanding, entry):
            frame = inspect.currentframe().f_back
            assert frame.f_code is coach.run.__code__
            local = frame.f_locals
            captured["coach"] = (coach.COACH_SYSTEM.format(category=local["category"]), local["content"])
            return original_coach_mock(understanding, entry)
        def capture_model(system, content, schema, **kwargs):
            if schema is schemas.Plan:
                captured["planner"] = (system, content)
                return mock.fake(schema, content)
            assert schema is schemas.ScriptOut
            captured["author"] = (system, content)
            raise CapturedAuthor()
        with patch.object(coach, "mock_playbook", capture_coach), \
                patch.object(plan.claude, "structured", side_effect=capture_model), \
                patch("server.llm.gemini.client", side_effect=blocked), \
                patch("server.llm.runware._post", side_effect=blocked), \
                patch("server.llm.claude._client_opts", side_effect=blocked):
            coach.run(demo["id"], lambda message: None)
            plan.run(demo["id"], lambda message: None)
            try:
                author.run(demo["id"], lambda message: None)
            except CapturedAuthor:
                pass
            else:
                raise AssertionError("Author did not reach its intercepted model boundary")
        expected_systems = {
            "coach": coach.COACH_SYSTEM.format(category=category),
            "planner": plan.PLAN_SYSTEM.format(principles=principles.PRINCIPLES, states=principles.CUSTOMER_STATES,
                shape=principles.PITCH_SHAPE, proof_block=principles.PROOF_BLOCK,
                audience=principles.audience_instruction(audience), language=principles.language_instruction(language)),
            "author": author.AUTHOR_SYSTEM.format(principles=principles.PRINCIPLES, author_craft=principles.AUTHOR_CRAFT,
                ladder=principles.TRANSLATION_LADDER, signposts=" | ".join(principles.SIGNPOSTS),
                audience=principles.audience_instruction(audience), language=principles.language_instruction(language)),
        }
        valid = set(captured) == set(expected_systems)
        for stage, (system, content) in captured.items():
            valid = valid and system == expected_systems[stage] and "REJECTED CLAIM" not in content
            valid = valid and all(value in content for value in ("160 PS", "Turbo automatic only; exact source unit", "page 4 / turbo column"))
            valid = valid and not re.search(r"\{(?:category|principles|author_craft|ladder|signposts|audience|language|states|shape|proof_block)\}", system)
            if stage != "coach":
                valid = valid and principles.PRINCIPLES in system and principles.audience_instruction(audience) in system
        check(f"actual Coach/Planner/Author envelopes: {category}, {audience}, {language}", valid)

